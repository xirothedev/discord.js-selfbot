// Dev-time generator (runs under Bun): derives the raw-string -> Events-member
// snapshot from the library's real Events object and writes
// src/generated/event-constants.ts. On duplicate values the UPPER_SNAKE key wins.

import path from 'node:path';
import { Events } from '../../discord-ts-selfbot/src/util/Events';

const target = path.join(
  import.meta.dirname,
  '../src/generated/event-constants.ts'
);

const byValue = new Map<string, string>();
for (const [key, value] of Object.entries(Events)) {
  if (typeof value !== 'string') {
    continue;
  }
  const existing = byValue.get(value);
  if (!existing || (!existing.includes('_') && key.includes('_'))) {
    byValue.set(value, key);
  }
}

// Keys are emitted unquoted when they are valid identifiers, matching the
// repo formatter's `quoteProps: "as-needed"` rule so generate:check is stable.
const asKey = (value: string): string =>
  /^[A-Za-z_$][\w$]*$/u.test(value) ? value : JSON.stringify(value);

const entries = [...byValue.entries()]
  .toSorted(([first], [second]) => first.localeCompare(second))
  .map(([value, key]) => `  ${asKey(value)}: '${key}',`)
  .join('\n');

const file = `// Auto-generated by scripts/generate-event-map.ts — do not edit.
// Maps a v13 raw event name string to the Events member whose value equals it
// (value-preserving rewrites only; UPPER_SNAKE preferred on duplicates).
export const eventConstants: Record<string, string> = {
${entries}
};
`;

const source = await Bun.file(target)
  .text()
  .catch(() => '');
if (Bun.argv.includes('--check')) {
  if (source !== file) {
    console.error('event-constants.ts is stale; run `bun run generate`');
    process.exit(1);
  }
  console.log('event-constants.ts is current');
} else {
  await Bun.write(target, file);
  console.log(`wrote ${byValue.size} event mappings`);
}
