import { defineConfig } from "oxlint";
import core from "ultracite/oxlint/core";
import next from "ultracite/oxlint/next";
import react from "ultracite/oxlint/react";

// Bun's linter has no jsdoc plugin. Drop those rules so every run is clean.
const plugins = (core.plugins ?? []).filter((name) => name !== "jsdoc");
const rules = Object.fromEntries(
  Object.entries(core.rules ?? {}).filter(
    ([name]) => !name.startsWith("jsdoc/")
  )
);

export default defineConfig({
  ...core,
  ignorePatterns: [
    ...(core.ignorePatterns ?? []),
    // Tooling config is not app code.
    "oxlint.config.ts",
    // Public declaration files mirror discord.js v14; schema:check and docs:check cover them.
    "packages/discord-ts-selfbot/typings/**",
    // Generated by tools/schema/generate.ts; currency is checked by schema:check.
    "packages/discord-ts-selfbot/src/types/entities/**",
    "packages/discord-ts-selfbot/src/types/schema.ts",
  ],
  overrides: [
    ...(core.overrides ?? []),
    {
      files: ["apps/docs/**/*.{ts,tsx}"],
      plugins: ["nextjs", "react", "react-perf", "jsx-a11y"],
      rules: {
        ...react.rules,
        ...next.rules,
      },
    },
  ],
  plugins,
  rules: {
    ...rules,
    // Deliberate repo patterns. Fixing these would break the public API or runtime order.
    "unicorn/filename-case": "off", // PascalCase class files mirror discord.js v14.
    "no-bitwise": "off", // Permission and flag bitfields are the domain.
    "import/first": "off", // `const { X } = module` lines protect circular dependencies.
    "import/no-named-as-default": "off", // Default plus named exports are kept for v14 parity.
    "import/no-named-as-default-member": "off",
    "import/no-cycle": "off", // The discord.js object graph is circular by design.
    "func-style": "off", // The library mixes declarations and class methods.
    "class-methods-use-this": "off", // Public class shape must stay stable.
    "unicorn/prefer-event-target": "off", // EventEmitter is the public API.
    "unicorn/prefer-set-has": "off", // The fix changes array types and breaks callers.
    "prefer-object-spread": "off", // Object.assign keeps the NodeJS.ProcessEnv type for shard env.
    "no-plusplus": "off", // The fixer changes `i++ % 2` into broken arithmetic.
    "no-unexpected-multiline": "off", // The fixer inserts a semicolon and breaks chained bracket calls.
    "typescript/class-literal-property-style": "off", // The fixer turns overridden getters into properties.
    eqeqeq: ["error", "always", { null: "ignore" }], // `!= null` also excludes undefined.
    "require-await": "off", // Dropping async changes promise rejection behavior.
    // Team baseline.
    "max-lines": ["error", { max: 300 }],
    "id-length": [
      "error",
      { exceptions: ["u", "r", "k", "e", "s", "w", "d", "n", "o"], min: 2 },
    ],
  },
});
