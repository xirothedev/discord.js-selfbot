import { frontmatter } from "./render-shared";

export interface ApiIndexArea {
  id: string;
  title: string;
  count: number;
}

export interface ApiIndexInput {
  areas: ApiIndexArea[];
  aliases: string[];
  external: string[];
  skipped?: string[];
  version: string;
}

export interface AreaIndexInput {
  title: string;
  description: string;
  items: { title: string; href: string; description?: string }[];
}

export function renderAreaIndex(input: AreaIndexInput): string {
  const cards = input.items
    .map((item) => {
      const description = item.description
        ? ` description={${JSON.stringify(item.description)}}`
        : "";
      return `  <Card title={${JSON.stringify(item.title)}} href={${JSON.stringify(item.href)}}${description} />`;
    })
    .join("\n");

  return [
    frontmatter({ description: input.description, title: input.title }),
    "{/* This file is generated by apps/docs/scripts/generate-api.ts. Do not edit. */}",
    "",
    input.description,
    "",
    "<Cards>",
    cards,
    "</Cards>",
  ].join("\n");
}

export function renderApiIndex(input: ApiIndexInput): string {
  const cards = input.areas
    .filter((area) => area.count > 0)
    .map(
      (area) =>
        `  <Card title="${area.title} (${area.count})" href="/docs/api/${area.id}" />`
    )
    .join("\n");

  return [
    frontmatter({
      description: `Public API for discord-ts-selfbot ${input.version}, generated from the API prose store and typings.`,
      title: "API Reference",
    }),
    "{/* This file is generated by apps/docs/scripts/generate-api.ts. Do not edit. */}",
    "",
    `This reference covers the public exports of \`discord-ts-selfbot@${input.version}\`.`,
    "Descriptions come from the API prose store. Signatures come from the public typings.",
    "",
    "## Sections",
    "",
    "<Cards>",
    cards,
    "</Cards>",
    "",
    "## What is included",
    "",
    "- Classes, functions, variables, interfaces, and type aliases reachable from `src/index.ts`.",
    "- One page per public class, grouped by area.",
    "- Type-only exports grouped by domain.",
    "",
    "## What is excluded",
    "",
    "- v13 aliases. See the [migration guide](/docs/getting-started/migration-v13) for the rename table.",
    "- Re-exports from `@discordjs/builders` and other external packages. Read the upstream discord.js docs for those.",
    "",
    input.aliases.length
      ? `<Callout type="info" title="v13 aliases">${input.aliases.join(", ")} are deprecated aliases. Use the v14 names.</Callout>`
      : "",
    input.external.length
      ? `<Callout type="info" title="External re-exports">${input.external.join(
          ", "
        )} come from @discordjs/builders. Read the upstream docs for their API.</Callout>`
      : "",
    input.skipped?.length
      ? `<Callout type="info" title="Runtime exports without public typings">${input.skipped.join(
          ", "
        )} are exported at runtime but have no declaration in typings/index.d.ts. They are omitted from this reference.</Callout>`
      : "",
  ]
    .filter(Boolean)
    .join("\n\n");
}
