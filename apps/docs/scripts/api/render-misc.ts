import {
  escapeMdx,
  frontmatterDescription,
  inlineCode,
  renderExamples,
  renderSummary,
} from './comment';
import {
  frontmatter,
  mergeSignature,
  renderParameterList,
  signatureLine,
} from './render-shared';
import { renderType } from './render-type';
import { Kind } from './types';
import type { Reflection } from './types';

export interface MiscPageInput {
  name: string;
  source?: Reflection;
  typings?: Reflection;
  sourceUrl?: string;
}

export function renderFunctionPage(input: MiscPageInput): string {
  const sourceSignatures = input.source?.signatures ?? [];
  const typingsSignatures = input.typings?.signatures ?? [];
  const count = Math.max(sourceSignatures.length, typingsSignatures.length);
  const blocks: string[] = [];

  for (let index = 0; index < count; index += 1) {
    const merged = mergeSignature(
      sourceSignatures[index],
      typingsSignatures[index]
    );
    blocks.push(
      [
        renderSummary(merged.comment),
        '```ts',
        signatureLine(merged, `function ${input.name}`),
        '```',
        renderParameterList(merged.parameters),
        renderExamples(merged.comment),
      ]
        .filter(Boolean)
        .join('\n\n')
    );
  }

  return [
    frontmatter({
      description: frontmatterDescription(
        input.source?.comment ?? input.typings?.comment,
        `${input.name} API reference.`
      ),
      sourceUrl: input.sourceUrl,
      title: input.name,
    }),
    '{/* This file is generated by apps/docs/scripts/generate-api.ts. Do not edit. */}',
    '',
    input.sourceUrl
      ? `<Callout type="info" title="Source">[View source](${input.sourceUrl})</Callout>`
      : '',
    ...blocks,
  ]
    .filter(Boolean)
    .join('\n\n');
}

export function renderEnumPage(input: MiscPageInput): string {
  const members = input.source?.children ?? [];
  const rows = members
    .map(
      (member) =>
        `| ${inlineCode(member.name)} | ${inlineCode(renderType(member.type))} |`
    )
    .join('\n');

  return [
    frontmatter({
      description: frontmatterDescription(
        input.source?.comment,
        `${input.name} enum reference.`
      ),
      sourceUrl: input.sourceUrl,
      title: input.name,
    }),
    '{/* This file is generated by apps/docs/scripts/generate-api.ts. Do not edit. */}',
    '',
    input.sourceUrl
      ? `<Callout type="info" title="Source">[View source](${input.sourceUrl})</Callout>`
      : '',
    renderSummary(input.source?.comment),
    rows ? `| Name | Value |\n| --- | --- |\n${rows}` : '',
  ]
    .filter(Boolean)
    .join('\n\n');
}

export function renderVariablePage(input: MiscPageInput): string {
  const type = input.typings?.type ?? input.source?.type;
  const children = input.typings?.children ?? [];
  const childList = children
    .map((child) => {
      const description = renderSummary(child.comment);
      return `- ${inlineCode(`${child.name}: ${renderType(child.type)}`)}${description ? ` — ${escapeMdx(description)}` : ''}`;
    })
    .join('\n');

  return [
    frontmatter({
      description: frontmatterDescription(
        input.source?.comment ?? input.typings?.comment,
        `${input.name} API reference.`
      ),
      sourceUrl: input.sourceUrl,
      title: input.name,
    }),
    '{/* This file is generated by apps/docs/scripts/generate-api.ts. Do not edit. */}',
    '',
    input.sourceUrl
      ? `<Callout type="info" title="Source">[View source](${input.sourceUrl})</Callout>`
      : '',
    renderSummary(input.source?.comment ?? input.typings?.comment),
    type ? `**Type:** ${inlineCode(renderType(type))}` : '',
    childList,
  ]
    .filter(Boolean)
    .join('\n\n');
}

export function isClassLike(reflection: Reflection | undefined): boolean {
  return reflection?.kind === Kind.Class;
}

export function renderEnumMembersPage(input: {
  name: string;
  members: Reflection[];
  description?: string;
  sourceUrl?: string;
}): string {
  const rows = input.members
    .map(
      (member) =>
        `| ${inlineCode(member.name)} | ${inlineCode(renderType(member.type))} |`
    )
    .join('\n');

  return [
    frontmatter({
      description: frontmatterDescription(
        undefined,
        `${input.name} enum reference.`
      ),
      sourceUrl: input.sourceUrl,
      title: input.name,
    }),
    '{/* This file is generated by apps/docs/scripts/generate-api.ts. Do not edit. */}',
    '',
    input.sourceUrl
      ? `<Callout type="info" title="Source">[View source](${input.sourceUrl})</Callout>`
      : '',
    input.description ?? '',
    rows ? `| Name | Value |\n| --- | --- |\n${rows}` : '',
  ]
    .filter(Boolean)
    .join('\n\n');
}
